import { randomUUID } from 'node:crypto';
import type { Job } from 'bullmq';

import { GurusthalamLogger } from '@gurusthalam/logger';

import { NotificationProviderRegistry } from '../providers/notification/notification-provider.registry.js';

import { NotificationFailureClassification } from '../providers/notification/notification-provider-result.types.js';

import { NotificationPersistenceService } from '../notifications/notification-persistence.service.js';

import { NotificationDeliveryPersistenceService } from '../notifications/notification-delivery-persistence.service.js';

import { NotificationAttemptOwnershipLostError } from '../notifications/notification-attempt-ownership.error.js';

import { NotificationDeliveryAcceptanceUncertainError } from '../notifications/notification-delivery-acceptance-uncertain.error.js';

import { createNotificationDeliveryKey } from '../notifications/notification-delivery-key.js';

import { NotificationFallbackExecutor } from '../notifications/notification-fallback.executor.js';

import {
  decideNotificationRetry,
  getNotificationRetryPolicy,
} from '../notifications/notification-retry.policy.js';

import { NotificationMetricsService } from '../notifications/notification-metrics.service.js';

export const NOTIFICATION_CHANNELS = {
  EMAIL: 'email',

  IN_APP: 'in-app',

  PUSH: 'push',
} as const;

export type NotificationChannel =
  (typeof NOTIFICATION_CHANNELS)[keyof typeof NOTIFICATION_CHANNELS];

export type NotificationJsonPrimitive = string | number | boolean | null;

export type NotificationJsonValue =
  | NotificationJsonPrimitive
  | NotificationJsonValue[]
  | {
      [key: string]: NotificationJsonValue;
    };

export interface NotificationRecipient {
  readonly userId: string;

  readonly email?: string;

  readonly deviceTokens?: readonly string[];
}

export interface NotificationFallbackMetadata {
  readonly planId: string;

  readonly orchestrationId: string;

  readonly primary: NotificationChannel;

  readonly fallbacks: readonly NotificationChannel[];

  readonly sequence: readonly NotificationChannel[];

  readonly position: number;
}

export interface NotificationJobData {
  readonly notificationId: string;

  readonly channel: NotificationChannel;

  readonly recipient: NotificationRecipient;

  readonly subject?: string;

  readonly title?: string;

  readonly body: string;

  readonly template?: string;

  readonly templateData?: {
    [key: string]: NotificationJsonValue;
  };

  readonly idempotencyKey: string;

  /**
   * Normal notification jobs omit this field and the processor
   * derives the canonical delivery key.
   *
   * Replay jobs provide a new delivery key so they create a
   * distinct NotificationDelivery record.
   */
  readonly deliveryKey?: string;

  /**
   * Immutable fallback plan metadata generated by the API
   * orchestration layer.
   *
   * The worker uses this metadata only after the primary
   * channel has exhausted its configured retry policy.
   */
  readonly fallbackMetadata?: NotificationFallbackMetadata;
}

export interface NotificationJobResult {
  readonly processed: true;

  readonly notificationId: string;

  readonly channel: NotificationChannel;

  readonly provider: string;

  readonly messageId: string;
}

class ClassifiedNotificationError extends Error {
  constructor(
    message: string,

    readonly classification:
      'RETRYABLE' | 'RATE_LIMITED' | 'NON_RETRYABLE' | 'PERMANENT',

    readonly provider: string,

    readonly errorCode?: string,

    readonly retryAfterMs?: number,
  ) {
    super(message);

    this.name = 'ClassifiedNotificationError';
  }
}

export class NotificationProcessor {
  private readonly fallbackExecutor: NotificationFallbackExecutor;

  constructor(
    private readonly logger: GurusthalamLogger,

    private readonly providerRegistry: NotificationProviderRegistry,

    private readonly persistence: NotificationPersistenceService,

    private readonly deliveryPersistence: NotificationDeliveryPersistenceService,

    private readonly metrics: NotificationMetricsService,
  ) {
    this.fallbackExecutor = new NotificationFallbackExecutor(
      logger,

      providerRegistry,

      deliveryPersistence,

      metrics,
    );
  }

  async process(job: Job<NotificationJobData>): Promise<NotificationJobResult> {
    const startedAt = Date.now();

    const notification = job.data;

    const isReplay = notification.deliveryKey !== undefined;

    const attempt = job.attemptsMade + 1;

    const parentOwnershipToken = randomUUID();
    const deliveryOwnershipToken = randomUUID();

    const retryPolicy = getNotificationRetryPolicy();

    this.metrics.incrementProcessing();

    this.logger.info(`Processing notification job: ${job.id ?? 'unknown'}`, {
      operation: 'notification.process',

      service: notification.channel,

      ...(isReplay
        ? {
            deliveryKey: notification.deliveryKey,
          }
        : {}),
    });

    const provider = this.providerRegistry.get(notification.channel);

    const providerName = this.getProviderName(notification.channel);

    const deliveryKey =
      notification.deliveryKey ??
      createNotificationDeliveryKey(
        notification.notificationId,

        notification.channel,

        providerName,
      );

    await this.deliveryPersistence.createIfMissing(
      notification.notificationId,

      deliveryKey,

      providerName,

      this.toPrismaChannel(notification.channel),
    );

    let providerOutcomeUncertain = false;

    try {
      const deliveryRecord =
        await this.deliveryPersistence.getByDeliveryKey(deliveryKey);

      if (
        deliveryRecord?.status === 'SENT' &&
        deliveryRecord.providerMessageId
      ) {
        if (!isReplay) {
          try {
            await this.persistence.reconcileSentFromDelivery(
              notification.notificationId,
              deliveryRecord.provider,
              deliveryRecord.providerMessageId,
            );
          } catch (reconciliationError: unknown) {
            // The delivery is durably SENT; a failed best-effort parent repair
            // must not turn that successful delivery into a provider failure.
            this.logger.warn(
              `Could not reconcile notification lifecycle from sent delivery: ${notification.notificationId}; reason: ${
                reconciliationError instanceof Error
                  ? reconciliationError.message
                  : String(reconciliationError)
              }`,
              {
                operation: 'notification.delivery.parent_reconciliation_failed',
                service: deliveryRecord.provider,
              },
            );
          }
        }

        this.metrics.incrementIdempotentHits();

        this.metrics.incrementProviderIdempotentHits(providerName);

        const latency = Date.now() - startedAt;

        this.metrics.recordLatency(latency);

        this.metrics.recordProviderLatency(
          providerName,

          latency,
        );

        this.logger.info(
          `Notification delivery already completed: ${notification.notificationId}`,
          {
            operation: 'notification.delivery.idempotent_skip',

            service: providerName,

            ...(isReplay
              ? {
                  deliveryKey,
                }
              : {}),
          },
        );

        return {
          processed: true,

          notificationId: notification.notificationId,

          channel: notification.channel,

          provider: providerName,

          messageId: deliveryRecord.providerMessageId,
        };
      }

      /*
       * Check the persisted delivery before claiming the parent.
       * An already-SENT delivery is an idempotent success and must
       * never fail merely because the parent is already terminal.
       */
      if (!isReplay) {
        // Both ownership claims commit together before any provider I/O.
        await this.persistence.claimPrimaryAttempt(
          notification,
          deliveryKey,
          attempt,
          parentOwnershipToken,
          deliveryOwnershipToken,
        );
      } else {
        // Replay jobs intentionally own only their distinct delivery row.
        await this.deliveryPersistence.markProcessing(
          deliveryKey,
          attempt,
          deliveryOwnershipToken,
        );
      }

      const providerStartedAt = Date.now();

      let delivery;

      try {
        // This durable marker must commit before provider I/O. If the worker
        // crashes after this point, the delivery cannot be lease-reclaimed
        // automatically because the provider may have accepted it.
        await this.deliveryPersistence.markProviderSubmissionStarted(
          deliveryKey,
          deliveryOwnershipToken,
        );
        providerOutcomeUncertain = true;

        delivery = await provider.send(
          notification,

          {
            deliveryKey,
          },
        );
      } catch (error: unknown) {
        this.metrics.incrementProviderErrorsFor(providerName);

        this.metrics.recordProviderLatency(
          providerName,

          Date.now() - providerStartedAt,
        );

        throw error;
      }

      const providerLatency = Date.now() - providerStartedAt;

      this.metrics.recordProviderLatency(
        providerName,

        providerLatency,
      );

      switch (delivery.classification) {
        case NotificationFailureClassification.SUCCESS: {
          if (delivery.accepted !== true) {
            this.metrics.incrementProviderErrorsFor(providerName);

            throw new Error(
              `Provider "${delivery.provider}" reported SUCCESS without accepting notification "${notification.notificationId}".`,
            );
          }

          const messageId = delivery.messageId;

          if (typeof messageId !== 'string' || messageId.trim().length === 0) {
            this.metrics.incrementProviderErrorsFor(providerName);

            throw new Error(
              `Provider "${delivery.provider}" reported SUCCESS without a valid messageId for notification "${notification.notificationId}".`,
            );
          }

          await this.deliveryPersistence.markSent(
            deliveryKey,
            deliveryOwnershipToken,
            messageId,
          );
          providerOutcomeUncertain = false;

          if (!isReplay) {
            await this.persistence.markSent(
              notification.notificationId,
              parentOwnershipToken,
              delivery.provider,
              messageId,
            );
          }

          this.metrics.incrementSent();

          this.metrics.incrementProviderSent(providerName);

          this.metrics.recordLatency(Date.now() - startedAt);

          this.logger.info(
            `Notification delivered: ${notification.notificationId}`,
            {
              operation: 'notification.delivered',

              service: delivery.provider,

              ...(isReplay
                ? {
                    deliveryKey,
                  }
                : {}),
            },
          );

          return {
            processed: true,

            notificationId: notification.notificationId,

            channel: notification.channel,

            provider: delivery.provider,

            messageId,
          };
        }

        case NotificationFailureClassification.RETRYABLE:
        case NotificationFailureClassification.RATE_LIMITED: {
          // A structured rejection is a definite provider outcome; normal
          // retry policy is safe and markFailed clears the submission marker.
          providerOutcomeUncertain = false;
          const reason =
            delivery.errorMessage ??
            `Notification provider returned ${delivery.classification}.`;

          throw new ClassifiedNotificationError(
            reason,

            delivery.classification,

            delivery.provider,

            delivery.errorCode,

            delivery.retryAfterMs,
          );
        }

        case NotificationFailureClassification.NON_RETRYABLE:
        case NotificationFailureClassification.PERMANENT: {
          providerOutcomeUncertain = false;
          const reason =
            delivery.errorMessage ??
            `Notification provider returned ${delivery.classification}.`;

          throw new ClassifiedNotificationError(
            reason,

            delivery.classification,

            delivery.provider,

            delivery.errorCode,

            delivery.retryAfterMs,
          );
        }
      }
    } catch (error: unknown) {
      /*
       * Ownership loss is a concurrency signal, not a provider failure.
       * Do not mutate delivery/parent state or schedule a retry from this
       * stale attempt; the current owner is responsible for its outcome.
       */
      if (error instanceof NotificationAttemptOwnershipLostError) {
        throw error;
      }

      const message = error instanceof Error ? error.message : String(error);

      if (providerOutcomeUncertain) {
        // Do not mark failed/retrying and do not invoke fallback: the provider
        // may have accepted the message. Persist ACCEPTANCE_UNKNOWN where
        // possible. Even if that write fails, providerSubmissionStartedAt
        // remains durable and blocks automatic lease reclamation.
        try {
          await this.deliveryPersistence.markAcceptanceUnknown(
            deliveryKey,
            deliveryOwnershipToken,
            message,
          );
        } catch (stateError: unknown) {
          this.logger.error(
            `Could not persist acceptance-unknown state for delivery "${deliveryKey}"; automatic retry remains blocked by the provider-submission marker.`,
            stateError,
            {
              operation:
                'notification.delivery.acceptance_unknown_persist_failed',
              service: providerName,
            },
          );
        }

        this.metrics.incrementProviderErrorsFor(providerName);
        this.metrics.recordLatency(Date.now() - startedAt);
        this.logger.error(
          `Notification delivery outcome is unknown and automatic resend is blocked: ${notification.notificationId}; deliveryKey: ${deliveryKey}`,
          error,
          {
            operation: 'notification.delivery.acceptance_unknown',
            service: providerName,
          },
        );

        // Complete the queue job to prevent BullMQ retry from resubmitting it.
        // This synthetic identifier is explicitly NOT a provider message ID.
        return {
          processed: true,
          notificationId: notification.notificationId,
          channel: notification.channel,
          provider: providerName,
          messageId: `acceptance-unknown:${deliveryKey}`,
        };
      }

      if (error instanceof ClassifiedNotificationError) {
        const decision = decideNotificationRetry(
          error.classification,

          attempt,

          retryPolicy,

          error.retryAfterMs,
        );

        if (decision.shouldRetry) {
          await this.deliveryPersistence.markFailed(
            deliveryKey,
            deliveryOwnershipToken,
            message,
          );

          if (!isReplay) {
            await this.persistence.markRetrying(
              notification.notificationId,
              parentOwnershipToken,
              message,
              attempt,
            );
          }

          this.metrics.incrementRetrying();

          this.metrics.incrementProviderRetrying(error.provider);

          this.logger.warn(
            `Notification retry scheduled [${error.classification}] attempt ${attempt}/${retryPolicy.maxAttempts} delay=${decision.delayMs}ms: ${notification.notificationId}`,
            {
              operation: 'notification.retrying',

              service: error.provider,

              ...(isReplay
                ? {
                    deliveryKey,
                  }
                : {}),
            },
          );

          /*
           * BullMQ receives this Error and invokes the custom
           * backoff strategy from queue.policy.ts. For a
           * RATE_LIMITED error the strategy reads retryAfterMs.
           */
          throw error;
        }

        /*
         * The primary channel has no retry left.
         *
         * Fallback is intentionally evaluated here, after
         * the existing retry policy has been exhausted.
         */
        if (!isReplay && notification.fallbackMetadata !== undefined) {
          let fallbackResult;

          try {
            fallbackResult = await this.fallbackExecutor.execute(
              notification,

              notification.fallbackMetadata,

              attempt,
            );
          } catch (fallbackError: unknown) {
            if (
              fallbackError instanceof
              NotificationDeliveryAcceptanceUncertainError
            ) {
              /*
               * A fallback submission may already have been accepted. Complete
               * this BullMQ job instead of throwing and replaying the primary.
               * Persist the parent lifecycle as uncertain where possible.
               */
              try {
                await this.persistence.markAcceptanceUnknown(
                  notification.notificationId,
                  parentOwnershipToken,
                  fallbackError.message,
                  attempt,
                );
              } catch (stateError: unknown) {
                this.logger.error(
                  `Could not persist acceptance-unknown parent state for notification "${notification.notificationId}"; the job will still complete to prevent an automatic resend.`,
                  stateError,
                  {
                    operation:
                      'notification.fallback.parent_acceptance_unknown_persist_failed',
                    service: notification.channel,
                  },
                );
              }

              this.metrics.incrementProviderErrorsFor(providerName);
              this.metrics.recordLatency(Date.now() - startedAt);
              this.logger.error(
                `Notification fallback outcome is unknown; automatic resend is blocked: ${notification.notificationId}; deliveryKey: ${fallbackError.deliveryKey}`,
                fallbackError,
                {
                  operation: 'notification.fallback.acceptance_unknown',
                  service: notification.channel,
                },
              );

              return {
                processed: true,
                notificationId: notification.notificationId,
                channel: notification.channel,
                provider: providerName,
                messageId: `acceptance-unknown:${fallbackError.deliveryKey}`,
              };
            }

            throw fallbackError;
          }

          if (fallbackResult !== null) {
            await this.persistence.markSent(
              notification.notificationId,
              parentOwnershipToken,
              fallbackResult.provider,
              fallbackResult.messageId,
            );

            this.metrics.incrementSent();

            this.metrics.incrementProviderSent(fallbackResult.provider);

            this.metrics.recordLatency(Date.now() - startedAt);

            this.logger.info(
              `Notification recovered through fallback channel "${fallbackResult.channel}": ${notification.notificationId}`,
              {
                operation: 'notification.fallback.recovered',

                service: fallbackResult.provider,
              },
            );

            return {
              processed: true,

              notificationId: notification.notificationId,

              channel: fallbackResult.channel,

              provider: fallbackResult.provider,

              messageId: fallbackResult.messageId,
            };
          }
        }

        await this.deliveryPersistence.markFailed(
          deliveryKey,
          deliveryOwnershipToken,
          message,
        );

        if (!isReplay) {
          await this.persistence.markFailed(
            notification.notificationId,
            parentOwnershipToken,
            message,
            attempt,
          );
        }

        this.metrics.incrementFailed();

        this.metrics.incrementProviderFailed(error.provider);

        this.metrics.recordLatency(Date.now() - startedAt);

        this.logger.error(
          `Notification terminal failure [${error.classification}] attempt ${attempt}/${retryPolicy.maxAttempts}: ${notification.notificationId}`,
          error,
          {
            operation: 'notification.failed',

            service: error.provider,

            ...(isReplay
              ? {
                  deliveryKey,
                }
              : {}),
          },
        );

        return {
          processed: true,

          notificationId: notification.notificationId,

          channel: notification.channel,

          provider: error.provider,

          messageId: `failed-${notification.notificationId}`,
        };
      }

      this.metrics.incrementProviderErrorsFor(providerName);

      const decision = decideNotificationRetry(
        NotificationFailureClassification.RETRYABLE,

        attempt,

        retryPolicy,
      );

      if (decision.shouldRetry) {
        await this.deliveryPersistence.markFailed(
          deliveryKey,
          deliveryOwnershipToken,
          message,
        );

        if (!isReplay) {
          await this.persistence.markRetrying(
            notification.notificationId,
            parentOwnershipToken,
            message,
            attempt,
          );
        }

        this.metrics.incrementRetrying();

        this.metrics.incrementProviderRetrying(providerName);

        this.logger.error(
          `Notification infrastructure retry scheduled attempt ${attempt}/${retryPolicy.maxAttempts}: ${notification.notificationId}`,
          error,
          {
            operation: 'notification.retrying',

            service: notification.channel,

            ...(isReplay
              ? {
                  deliveryKey,
                }
              : {}),
          },
        );
      } else {
        /*
         * An unexpected infrastructure/provider transport error
         * is not a classified provider failure. Keep the
         * existing infrastructure retry/terminal behavior.
         *
         * Fallback is intentionally not triggered here because
         * the provider classification contract was not reached.
         */
        await this.deliveryPersistence.markFailed(
          deliveryKey,
          deliveryOwnershipToken,
          message,
        );

        if (!isReplay) {
          await this.persistence.markFailed(
            notification.notificationId,
            parentOwnershipToken,
            message,
            attempt,
          );
        }

        this.metrics.incrementFailed();

        this.metrics.incrementProviderFailed(providerName);

        this.metrics.recordLatency(Date.now() - startedAt);

        this.logger.error(
          `Notification infrastructure retry limit reached: ${notification.notificationId}`,
          error,
          {
            operation: 'notification.failed',

            service: providerName,

            ...(isReplay
              ? {
                  deliveryKey,
                }
              : {}),
          },
        );
      }

      throw error;
    }
  }

  private getProviderName(channel: NotificationChannel): string {
    switch (channel) {
      case 'email':
        return 'development-email';

      case 'in-app':
        return 'development-in-app';

      case 'push':
        return 'development-push';
    }
  }

  private toPrismaChannel(
    channel: NotificationJobData['channel'],
  ): 'EMAIL' | 'IN_APP' | 'PUSH' {
    switch (channel) {
      case 'email':
        return 'EMAIL';

      case 'in-app':
        return 'IN_APP';

      case 'push':
        return 'PUSH';
    }
  }
}
